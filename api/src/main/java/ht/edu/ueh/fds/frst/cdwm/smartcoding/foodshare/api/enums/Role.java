/**
 * Création d'une énumération Role pour les utilisateurs de la plateforme.
 */

package ht.edu.ueh.fds.frst.cdwm.smartcoding.foodshare.api.enums;

/**
 * L'énumération Role représente les différents rôles pouvant être attribués
 * dans un contexte donné. Cette énumération sert à définir et
 * distinguer les responsabilités ou identités spécifiques.
 *
 * Valeurs énumérées:
 * - OFFREUR: Représente un fournisseur ou une personne/entité proposant une nourriture ou un produit alimentaire.
 * - ETUDIANT: Représente un étudiant du système.
 */
public enum Role {
    OFFREUR,
    ETUDIANT,
    ADMIN
}

