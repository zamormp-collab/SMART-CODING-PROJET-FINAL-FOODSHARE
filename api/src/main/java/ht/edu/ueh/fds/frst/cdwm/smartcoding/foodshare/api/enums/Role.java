/**
 * The Role enum represents the different roles that can be assigned
 * within a given context. This enumeration is used to define and
 * distinguish between specific responsibilities or identities.
 *
 * Enumerated values:
 * - OFFREUR: Represents a provider or an individual/entity offering something.
 * - ETUDIANT: Represents a student or a learner in the system.
 */
public enum Role {
    OFFREUR,
    ETUDIANT
}

